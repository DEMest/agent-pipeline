import { readFileSync } from 'node:fs';

/**
 * Читает текстовый файл репозитория, приводя переводы строк к LF.
 *
 * Зачем: файлы попадают в рабочее дерево через checkout, и на Windows Git отдаёт
 * их с CRLF. Тесты, сверяющие содержимое документов, из-за этого краснели локально
 * и оставались зелёными в CI на ubuntu — то есть ломались ровно у того, кто
 * склонировал репозиторий, и молчали там, где это можно было заметить.
 *
 * `.gitattributes` закрепляет LF за файлами проекта, но полагаться только на него
 * нельзя: настройки Git у клонирующего мы не контролируем.
 */
export function readText(path) {
  return readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
}
